def validate_spatial_metrics():
    """Validate spatial metrics (Steps 1 & 2)."""
    print("\n" + "#" * 70)
    print("  VALIDATING SPATIAL METRICS (Steps 1 & 2)")
    print("#" * 70)

    # Load Sapena's preprocessed data
    csv_file = PREPROCESSED_PATH / "spatial_metrics.csv"
    if not csv_file.exists():
        print(f"  Expected file not found: {csv_file}")
        return

    df_expected = pd.read_csv(csv_file)
    print(f"\nLoaded expected data: {len(df_expected)} FUAs")
    print(f"Columns: {list(df_expected.columns)}")

    # Note: Sapena's spatial_metrics.csv contains T2 metrics
    # T2 metrics: C_T2, DI_T2, AWSD_T2, SL_UC_T2, ER_UC_T2, C_UC_T2, DU_T2

    # Load our Step 2 output
    shp_t2 = OUTPUT_PATH / "Boundaries_SM_2014.shp"

    if shp_t2.exists():
        gdf_t2 = gpd.read_file(shp_t2)
        print(f"\nLoaded T2 output: {len(gdf_t2)} FUAs")

        # Compare T2 metrics
        t2_metrics = ['C_T2', 'DI_T2', 'AWSD_T2', 'SL_UC_T2', 'ER_UC_T2', 'C_UC_T2', 'DU_T2']

        results, detailed = compare_metrics(df_expected, gdf_t2, t2_metrics)
        print_comparison_report("T2 (2014) Spatial Metrics", results, detailed)
    else:
        print(f"\n  T2 output not found: {shp_t2}")
        print("  Run step2_spatial_metrics_2014.py first.")


