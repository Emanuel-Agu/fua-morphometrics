def compare_metrics(df_expected, df_actual, metric_cols, id_col='fuacode_si'):
    """
    Compare metrics between expected and actual DataFrames.

    Returns DataFrame with comparison results.
    """
    # Ensure id_col is string type for both
    df_expected = df_expected.copy()
    df_actual = df_actual.copy()
    df_expected[id_col] = df_expected[id_col].astype(str)
    df_actual[id_col] = df_actual[id_col].astype(str)

    # Get common columns
    exp_cols = [c for c in metric_cols if c in df_expected.columns]
    act_cols = [c for c in metric_cols if c in df_actual.columns]
    common_cols = list(set(exp_cols) & set(act_cols))

    if not common_cols:
        print(f"  No common metric columns found.")
        print(f"  Expected has: {exp_cols}")
        print(f"  Actual has: {act_cols}")
        return pd.DataFrame(), pd.DataFrame()

    # Merge on ID column
    merged = pd.merge(
        df_expected[[id_col] + common_cols],
        df_actual[[id_col] + common_cols],
        on=id_col,
        suffixes=('_expected', '_actual'),
        how='inner'
    )

    print(f"  Matched {len(merged)} FUAs")

    results = []
    for col in common_cols:
        exp_col = f"{col}_expected"
        act_col = f"{col}_actual"

        if exp_col not in merged.columns or act_col not in merged.columns:
            continue

        # Calculate differences
        merged[f'{col}_diff'] = merged[act_col] - merged[exp_col]
        merged[f'{col}_pct_diff'] = np.where(
            merged[exp_col] != 0,
            (merged[f'{col}_diff'] / merged[exp_col].abs()) * 100,
            np.where(merged[act_col] != 0, 100, 0)
        )

        # Summary statistics
        valid_mask = merged[exp_col].notna() & merged[act_col].notna()
        n_valid = valid_mask.sum()

        if n_valid > 0:
            mae = merged.loc[valid_mask, f'{col}_diff'].abs().mean()
            mape = merged.loc[valid_mask, f'{col}_pct_diff'].abs().mean()

            exp_vals = merged.loc[valid_mask, exp_col]
            act_vals = merged.loc[valid_mask, act_col]

            if exp_vals.std() > 0 and act_vals.std() > 0:
                corr = exp_vals.corr(act_vals)
            else:
                corr = np.nan

            within_tol = (merged.loc[valid_mask, f'{col}_pct_diff'].abs() <= TOLERANCE_PERCENT).sum()

            results.append({
                'Metric': col,
                'N_Valid': n_valid,
                'MAE': round(mae, 4),
                'MAPE (%)': round(mape, 2),
                'Correlation': round(corr, 4) if not np.isnan(corr) else 'N/A',
                f'Within {TOLERANCE_PERCENT}%': f"{(within_tol / n_valid) * 100:.1f}%"
            })

    return pd.DataFrame(results), merged


def print_comparison_report(title, results_df, detailed_df=None, show_worst=5):
    """Print a formatted comparison report."""
    print("\n" + "=" * 70)
    print(f"  {title}")
    print("=" * 70)

    if len(results_df) == 0:
        print("  No metrics to compare.")
        return

    print("\nSummary Statistics:")
    print("-" * 70)
    print(results_df.to_string(index=False))

    if detailed_df is not None and show_worst > 0 and len(detailed_df) > 0:
        print(f"\nTop {show_worst} FUAs with Largest Differences:")
        print("-" * 70)

        # Find metric columns with _pct_diff
        pct_cols = [c for c in detailed_df.columns if c.endswith('_pct_diff')]
        if pct_cols:
            # Average absolute percentage difference across all metrics
            detailed_df = detailed_df.copy()
            detailed_df['avg_pct_diff'] = detailed_df[pct_cols].abs().mean(axis=1)
            worst = detailed_df.nlargest(show_worst, 'avg_pct_diff')
            print(worst[['fuacode_si', 'avg_pct_diff']].to_string(index=False))


